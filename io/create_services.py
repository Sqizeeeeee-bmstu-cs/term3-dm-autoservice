# услуги, цена которых зависит от числа цилиндров: (название, мин., макс. для 4 цилиндров)
PER_CYLINDERS = [
    ("Замена свечей зажигания", 2_500, 4_500),
    ("Замена катушек зажигания", 2_500, 4_500),
    ("Замена форсунок", 7_000, 14_000),
    ("Ультразвуковая чистка форсунок", 5_000, 9_000),
    ("Замена ремня или цепи ГРМ", 15_000, 30_000),
    ("Снятие и установка двигателя (замена в сборе)", 60_000, 90_000),
]


def round_price(v):
    step = 50 if v < 5_000 else 100 if v < 50_000 else 500
    return int(round(v / step) * step)


def build(seed=SEED):
    rng = random.Random(seed)
    items = []
    for name, lo, hi in SIMPLE:
        items.append((name, round_price(rng.uniform(lo, hi))))
    for name, lo, hi in PER_CYLINDERS:
        for cyl, mult in CYL_VARIANTS:
            items.append((f"{name} ({cyl} цил.)", round_price(rng.uniform(lo, hi) * mult)))

    names = [n for n, _ in items]
    assert len(names) == len(set(names)), "есть дубликаты названий услуг"
    return [{"service_id": i, "name": n, "price": p} for i, (n, p) in enumerate(items, start=1)]


def main():
    parser = argparse.ArgumentParser(description="Создать файл данных для таблицы Service")
    parser.add_argument("--format", choices=["csv", "json"], default="csv")
    parser.add_argument("--seed", type=int, default=SEED)
    args = parser.parse_args()

    rows = build(args.seed)
    DATA_DIR.mkdir(exist_ok=True)
    out = DATA_DIR / f"service.{args.format}"
    if args.format == "csv":
        with open(out, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=["service_id", "name", "price"])
            w.writeheader()
            w.writerows(rows)
    else:
        with open(out, "w", encoding="utf-8") as f:
            json.dump(rows, f, ensure_ascii=False, indent=2)
    print(f"Записано {len(rows)} строк -> {out}")


if __name__ == "__main__":
    main()
    